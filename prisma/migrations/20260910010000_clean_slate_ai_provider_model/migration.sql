-- Catalog assertions make the enum dependency boundary explicit.  They fail
-- the migration if a legacy workspace trigger survives or if any recreated
-- clean guard was accidentally omitted.
DO $$
DECLARE
  stale_trigger TEXT;
  missing_trigger TEXT;
BEGIN
  SELECT format('%I on %I', expected.trigger_name, expected.relation_name)
    INTO stale_trigger
    FROM (VALUES
      ('AiProviderConnection_workspace_membership_guard', 'AiProviderConnection'),
      ('AiProviderConnection_workspace_owner_guard', 'AiProviderConnection'),
      ('WorkspaceMembership_ai_provider_membership_guard', 'WorkspaceMembership'),
      ('WorkspaceMembership_provider_owner_integrity_guard', 'WorkspaceMembership')
    ) AS expected(trigger_name, relation_name)
   WHERE EXISTS (
     SELECT 1
       FROM pg_trigger AS trigger_row
       JOIN pg_class AS relation_row ON relation_row.oid = trigger_row.tgrelid
       JOIN pg_namespace AS namespace_row ON namespace_row.oid = relation_row.relnamespace
      WHERE namespace_row.nspname = 'public'
        AND relation_row.relname = expected.relation_name
        AND trigger_row.tgname = expected.trigger_name
        AND NOT trigger_row.tgisinternal
   )
   LIMIT 1;
  IF stale_trigger IS NOT NULL THEN
    RAISE EXCEPTION 'CLEAN_SLATE_POSTCONDITION_FAILED: legacy trigger remains (%)', stale_trigger
      USING ERRCODE = 'check_violation';
  END IF;

  SELECT format('%I on %I', expected.trigger_name, expected.relation_name)
    INTO missing_trigger
    FROM (VALUES
      ('AiProviderConnection_personal_epoch_guard', 'AiProviderConnection'),
      ('PAD_provider_global_lock', 'AiProviderConnection'),
      ('PAD_provider_dependent_guard', 'AiProviderConnection'),
      ('MemoryPersonalProviderInvalidationGuard', 'AiProviderConnection'),
      ('ProjectAiProviderDelegation_active_integrity_guard', 'ProjectAiProviderDelegation'),
      ('ProjectAiEffectiveRouteSelection_integrity_guard', 'ProjectAiEffectiveRouteSelection'),
      ('ProjectAiProviderDelegation_personal_epoch_guard', 'ProjectAiProviderDelegation'),
      ('ProjectAiEffectiveRouteSelection_personal_epoch_guard', 'ProjectAiEffectiveRouteSelection'),
      ('PlatformTokenReservation_runtime_evidence_guard', 'PlatformTokenReservation'),
      ('ProviderCallAudit_runtime_evidence_guard', 'ProviderCallAudit'),
      ('WebAiGrant_personal_runtime_evidence_guard', 'WebAiGrant'),
      ('ProviderCallAudit_personal_runtime_evidence_guard', 'ProviderCallAudit'),
      ('MemoryIndexGeneration_personal_evidence_guard', 'MemoryIndexGeneration'),
      ('MemoryIndexPointer_personal_evidence_guard', 'MemoryIndexPointer')
    ) AS expected(trigger_name, relation_name)
   WHERE NOT EXISTS (
     SELECT 1
       FROM pg_trigger AS trigger_row
       JOIN pg_class AS relation_row ON relation_row.oid = trigger_row.tgrelid
       JOIN pg_namespace AS namespace_row ON namespace_row.oid = relation_row.relnamespace
      WHERE namespace_row.nspname = 'public'
        AND relation_row.relname = expected.relation_name
        AND trigger_row.tgname = expected.trigger_name
        AND NOT trigger_row.tgisinternal
   )
   LIMIT 1;
  IF missing_trigger IS NOT NULL THEN
    RAISE EXCEPTION 'CLEAN_SLATE_POSTCONDITION_FAILED: clean trigger missing (%)', missing_trigger
      USING ERRCODE = 'check_violation';
  END IF;
END;
$$;
