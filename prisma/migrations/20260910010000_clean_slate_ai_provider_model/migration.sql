DECLARE
  function_row RECORD;
  function_definition TEXT;
BEGIN
  FOR function_row IN
    SELECT p.oid, p.proname
      FROM pg_proc AS p
      JOIN pg_namespace AS n ON n.oid = p.pronamespace
     WHERE n.nspname = 'public'
       AND p.prokind = 'f'
       AND p.proname = ANY (ARRAY[
         'personal_memory_frozen_evidence_valid',
         'personal_memory_frozen_evidence_valid_without_epoch',
         'personal_memory_upstream_invalidation_guard',
         'personal_memory_index_live_evidence_valid',
         'personal_memory_index_live_evidence_valid_without_epoch',
         'personal_ai_grant_consistency_guard',
         'personal_ai_provider_call_consistency_guard',
         'runtime_ai_evidence_consistency_guard',
         'project_ai_provider_delegation_active_integrity_guard',
         'project_ai_effective_route_selection_integrity_guard',
         'project_ai_provider_connection_dependent_guard'
       ])
  LOOP
    function_definition := pg_get_functiondef(function_row.oid);
    IF function_definition ~ '"workspaceId"|"ownershipState"' THEN
      RAISE EXCEPTION
        'CLEAN_SLATE_PRECONDITION_FAILED: stale AI provider function % references removed columns',
        function_row.proname
        USING ERRCODE = 'check_violation';
    END IF;
  END LOOP;
END;
$$;

