-- Platform and personal provider identity is immutable.  Configuration and
-- credential rotation remain supported; only scope/owner/credential identity
-- is fenced.
CREATE OR REPLACE FUNCTION "ai_provider_connection_identity_guard"()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF OLD."scope" IS DISTINCT FROM NEW."scope"
     OR OLD."ownerUserId" IS DISTINCT FROM NEW."ownerUserId"
     OR OLD."credentialId" IS DISTINCT FROM NEW."credentialId"
  THEN
    RAISE EXCEPTION 'AI_PROVIDER_OWNERSHIP_IMMUTABLE'
      USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER "AiProviderConnection_identity_guard"
BEFORE UPDATE ON "AiProviderConnection"
FOR EACH ROW EXECUTE FUNCTION "ai_provider_connection_identity_guard"();

-- Enforce the two legal ownership shapes independently of ORM validation.
CREATE OR REPLACE FUNCTION "AiProviderConnection_owner_guard"()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF NEW."scope" = 'platform' AND NEW."ownerUserId" IS NOT NULL THEN
    RAISE EXCEPTION 'platform provider cannot have an owner'
      USING ERRCODE = 'check_violation';
  END IF;
  IF NEW."scope" = 'user' AND NEW."ownerUserId" IS NULL THEN
    RAISE EXCEPTION 'user provider requires an owner'
      USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER "AiProviderConnection_owner_guard"
BEFORE INSERT OR UPDATE ON "AiProviderConnection"
FOR EACH ROW EXECUTE FUNCTION "AiProviderConnection_owner_guard"();

