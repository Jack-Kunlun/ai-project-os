-- Rewrite live trigger/function definitions before dropping the columns.  The
-- function bodies are generated by PostgreSQL from the last applied schema,
-- so this keeps the forward migration valid for every supported clean-slate
-- starting database without editing historical migrations.
DO $$
DECLARE
  function_row RECORD;
  function_definition TEXT;
BEGIN
  FOR function_row IN
    SELECT p.oid
      FROM pg_proc AS p
      JOIN pg_namespace AS n ON n.oid = p.pronamespace
     WHERE n.nspname = 'public'
       AND p.prokind = 'f'
       AND p.proname = ANY (ARRAY[
         'personal_memory_frozen_evidence_valid',
         'personal_memory_frozen_evidence_valid_without_epoch',
         'personal_memory_upstream_invalidation_guard',
         'personal_memory_index_live_evidence_valid',
         'personal_memory_index_live_evidence_valid_without_epoch',
         'personal_ai_grant_consistency_guard',
         'personal_ai_provider_call_consistency_guard',
         'runtime_ai_evidence_consistency_guard',
         'project_ai_provider_delegation_active_integrity_guard',
         'project_ai_effective_route_selection_integrity_guard',
         'project_ai_provider_connection_dependent_guard',
         'personal_ai_provider_connection_epoch_guard',
         'personal_ai_delegation_epoch_guard',
         'personal_ai_selection_epoch_guard'
       ])
  LOOP
    function_definition := pg_get_functiondef(function_row.oid);
    function_definition := regexp_replace(
      function_definition,
      E'\\s+OR OLD\\."ownershipState"\\s+IS DISTINCT FROM\\s+NEW\\."ownershipState"',
      '',
      'g'
    );
    function_definition := regexp_replace(
      function_definition,
      E'\\s+OR OLD\\."workspaceId"\\s+IS DISTINCT FROM\\s+NEW\\."workspaceId"',
      '',
      'g'
    );
    function_definition := regexp_replace(
      function_definition,
      E'\\s+AND provider\\."workspaceId"\\s+IS NULL',
      '',
      'g'
    );
    function_definition := regexp_replace(
      function_definition,
      E'\\s+AND provider\\."ownershipState"\\s*=\\s*''confirmed''',
      '',
      'g'
    );
    function_definition := regexp_replace(
      function_definition,
      E'\\s*,\\s*"ownershipState"\\s+AS\\s+ownership_state\\s*,',
      ',',
      'g'
    );
    function_definition := replace(
      function_definition,
      '"scope" AS scope, "ownershipState" AS ownership_state, ',
      '"scope" AS scope, '
    );
    function_definition := replace(
      function_definition,
      'provider_row.ownership_state IS DISTINCT FROM ''confirmed'' OR ',
      ''
    );
    function_definition := regexp_replace(
      function_definition,
      E'provider_row\\.ownership_state\\s+IS DISTINCT FROM\\s+''confirmed''\\s+OR\\s+',
      '',
      'g'
    );
    EXECUTE function_definition;
  END LOOP;
END;
$$;

-- Fail closed if a historical function shape escaped the rewrite.  This
-- check runs while the legacy columns still exist, so its diagnostic remains
-- actionable instead of surfacing later as a missing-column error.
