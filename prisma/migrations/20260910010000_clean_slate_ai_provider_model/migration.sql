-- Clean-slate 0.2 AI provider model.
--
-- This is a forward migration.  The application has no production users yet,
-- but a migration must still fail closed if a legacy row is present instead of
-- silently discarding it.  Git/MCP ownership data and all AI runtime evidence
-- are intentionally outside this migration.

DO $$
BEGIN
  IF EXISTS (
    SELECT 1
      FROM "AppUser"
     WHERE "role"::text = 'member'
  ) THEN
    RAISE EXCEPTION
      'CLEAN_SLATE_PRECONDITION_FAILED: AppUserRole.member rows remain'
      USING ERRCODE = 'check_violation';
  END IF;

  IF EXISTS (
    SELECT 1
      FROM "AiProviderConnection"
     WHERE "scope"::text = 'workspace'
        OR "workspaceId" IS NOT NULL
  ) THEN
    RAISE EXCEPTION
      'CLEAN_SLATE_PRECONDITION_FAILED: workspace AI provider rows remain'
      USING ERRCODE = 'check_violation';
  END IF;

  IF to_regclass('"ProjectAiRoute"') IS NOT NULL
     AND EXISTS (SELECT 1 FROM "ProjectAiRoute") THEN
    RAISE EXCEPTION
      'CLEAN_SLATE_PRECONDITION_FAILED: ProjectAiRoute rows remain'
      USING ERRCODE = 'check_violation';
  END IF;

  IF to_regclass('"ProjectAiRouteRevision"') IS NOT NULL
     AND EXISTS (SELECT 1 FROM "ProjectAiRouteRevision") THEN
    RAISE EXCEPTION
      'CLEAN_SLATE_PRECONDITION_FAILED: ProjectAiRouteRevision rows remain'
      USING ERRCODE = 'check_violation';
  END IF;

  IF to_regclass('"AiProviderOwnershipAudit"') IS NOT NULL
     AND EXISTS (SELECT 1 FROM "AiProviderOwnershipAudit") THEN
    RAISE EXCEPTION
      'CLEAN_SLATE_PRECONDITION_FAILED: AiProviderOwnershipAudit rows remain'
      USING ERRCODE = 'check_violation';
  END IF;
END;
$$;

