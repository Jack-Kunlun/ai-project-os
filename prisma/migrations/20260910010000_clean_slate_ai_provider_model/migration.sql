-- Some early clean-slate development databases were created from the same
-- ownership shape with Prisma's generated constraint name
-- AiProviderConnection_owner_scope_check.  Keep the historical names above
-- explicit, then remove any remaining CHECK constraint on this table only when
-- its expression directly mentions a field that is about to be removed.  This
-- is an exact, non-CASCADE drop and prevents an old enum-typed CHECK from being
-- coerced while AiProviderScope is rebuilt.
DO $$
DECLARE
  constraint_row RECORD;
  constraint_definition TEXT;
BEGIN
  FOR constraint_row IN
    SELECT conname, oid
      FROM pg_constraint
     WHERE conrelid = 'public."AiProviderConnection"'::regclass
       AND contype = 'c'
  LOOP
    constraint_definition := pg_get_constraintdef(constraint_row.oid);
    IF constraint_definition ~ '"scope"'
       OR constraint_definition ~ '"workspaceId"'
       OR constraint_definition ~ '"ownershipState"'
    THEN
      EXECUTE format(
        'ALTER TABLE "AiProviderConnection" DROP CONSTRAINT %I',
        constraint_row.conname
      );
    END IF;
  END LOOP;
END;
$$;

